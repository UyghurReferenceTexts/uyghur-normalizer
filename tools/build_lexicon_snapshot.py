#!/usr/bin/env python3
"""
build_lexicon_snapshot.py — write tests/data/lexicon_snapshot.tsv.gz from the
audited headword spreadsheets of the 2009 imla dictionary [4] and the 2011
izahliq lughet [1].

One line per written form: form, source, row_id, status, scan.
  status = verified    the row has been checked against the scan by hand
           unverified  extracted by OCR + model and not yet checked

The extraction model was trained on web Uyghur, which is exactly the variety
these maps rewrite. An unverified headword may therefore show a web form the
book does not print. tests/test_lexicon.py fails only on VERIFIED rows and
merely lists the unverified ones for the headword audit.

    python tools/build_lexicon_snapshot.py \
        --imla imla_lughiti_2009.xlsx \
        --izahliq izahliq_lughet_2011_v1.xlsx izahliq_lughet_2011_v2.xlsx

Requires openpyxl (tooling only; the normalizer itself has no dependencies).
"""
import argparse, gzip, io, os, re, unicodedata
import openpyxl

SEP = re.compile(r'\s*(?:←|→|=|\||\(|\)|_|;|؛|،|,|:|\*|\d+)\s*')
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'tests', 'data', 'lexicon_snapshot.tsv.gz')


def phrases(cell):
    for p in SEP.split(unicodedata.normalize('NFC', str(cell))):
        p = re.sub(r'\s*-\s*', '-', p).strip(' -.')
        if p and re.search('[\u0620-\u06ff]', p) and not re.search('[A-Za-z]', p):
            yield p


def rows(path, sheet, cols):
    ws = openpyxl.load_workbook(path, read_only=True)[sheet]
    it = ws.iter_rows(values_only=True)
    head = next(it)
    idx = {k: head.index(v) for k, v in cols.items()}
    for r in it:
        yield {k: r[i] for k, i in idx.items()}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--imla', required=True)
    ap.add_argument('--izahliq', nargs='+', required=True)
    ap.add_argument('--out', default=OUT)
    a = ap.parse_args()

    seen, out = set(), []

    def add(form, src, rid, status, scan):
        st = 'verified' if str(status).strip().lower() == 'verified' else 'unverified'
        key = (form, src, rid)
        if key not in seen:
            seen.add(key)
            out.append((form, src, rid, st, scan or ''))

    for r in rows(a.imla, 'Imla Dictionary', dict(id='row_id', hw='Headword', sub='Sub-entries',
                                                 st='status_v1', scan='Source Column')):
        for col in ('hw', 'sub'):
            if r[col]:
                for p in phrases(r[col]):
                    add(p, '2009', r['id'], r['st'], r['scan'])
    for path in a.izahliq:
        for r in rows(path, 'Dictionary', dict(id='row_uid', val='Validity', hw='Headword',
                                              inf='Inflected Form', st='Status v1', scan='Source Column')):
            if r['val'] == 'ocr':
                continue
            for col in ('hw', 'inf'):
                if r[col]:
                    for p in phrases(r[col]):
                        add(p, '2011', r['id'], r['st'], r['scan'])

    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    # mtime=0 keeps the archive byte-identical when the data has not changed,
    # so a rebuild with no dictionary edits produces no git diff.
    with open(a.out, 'wb') as raw, gzip.GzipFile(fileobj=raw, mode='wb', mtime=0) as gz, \
            io.TextIOWrapper(gz, encoding='utf-8', newline='\n') as fh:
        fh.write('# lexicon_snapshot.tsv.gz — generated by tools/build_lexicon_snapshot.py; do not edit\n')
        fh.write('form\tsource\trow_id\tstatus\tscan\n')
        for t in out:
            fh.write('\t'.join(t) + '\n')
    v = sum(1 for t in out if t[3] == 'verified')
    print(f'{len(out)} forms ({v} verified) -> {a.out}')


if __name__ == '__main__':
    main()
