#!/usr/bin/env python3
"""
build_provenance.py — write normalizer/provenance.tsv: for every rule in the
three maps, the dictionary row that attests its replacement.

  origin   = where the rule comes from, when it is not a 2009 rule (usage map:
             the row of the 6-volume izahliq lughet [2])
  evidence = exact   the replacement itself is a headword or sub-entry (for the
                     usage and calque maps: the replacement after passes 2-3)
             stem    a headword is the replacement minus a suffix (≤ 8 chars)
             none    no attestation found: re-review this rule by hand
  verified = whether that row has been checked against its scan

Rows are preferred verified-first, then exact before stem, then [4] before
[1]. The 'verdict' column is for the reviewer and is carried over from an
existing provenance.tsv when the rule is unchanged.

    python tools/build_provenance.py
"""
import csv, gzip, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from uyghur_normalizer import load_map, build_pattern, process_text, Report  # noqa: E402

MAPS = ['usage_map.tsv', 'calque_map.tsv', 'era_map.tsv', 'imla_loan_map.tsv']
SNAP = os.path.join(ROOT, 'tests', 'data', 'lexicon_snapshot.tsv.gz')
OUT = os.path.join(ROOT, 'normalizer', 'provenance.tsv')
MAX_SFX = 8
COLS = ['map', 'variant', 'replacement', 'flags', 'origin', 'evidence', 'attested_as',
        'source', 'row_id', 'scan', 'verified', 'verdict']
ORIGIN = os.path.join(ROOT, 'normalizer', 'usage_map_origin.tsv')


def main():
    with gzip.open(SNAP, 'rt', encoding='utf-8') as fh:
        lex = list(csv.DictReader((l for l in fh if not l.startswith('#')), delimiter='\t',
                                  quoting=csv.QUOTE_NONE))
    rank = lambda r: (r['status'] != 'verified', r['source'] != '2009')
    best = {}
    for r in lex:
        if r['form'] not in best or rank(r) < rank(best[r['form']]):
            best[r['form']] = r

    old = {}
    if os.path.exists(OUT):
        with open(OUT, encoding='utf-8') as fh:
            for r in csv.DictReader((l for l in fh if not l.startswith('#')), delimiter='\t',
                                    quoting=csv.QUOTE_NONE):
                old[(r['map'], r['variant'], r['replacement'])] = r['verdict']

    origin = {}
    if os.path.exists(ORIGIN):
        with open(ORIGIN, encoding='utf-8') as fh:
            for r in csv.DictReader((l for l in fh if not l.startswith('#')), delimiter='\t'):
                origin[('usage_map.tsv', r['variant'])] = '[2] ' + r['row_id_1990s']

    # Passes 0-1 feed passes 2-3, so their evidence is the form that comes out.
    ortho = [build_pattern(load_map(os.path.join(ROOT, 'normalizer', m), m, quiet=True))
             for m in ('era_map.tsv', 'imla_loan_map.tsv')]

    rows = []
    for m in MAPS:
        for lhs, rhs_map, _lab, flags in load_map(os.path.join(ROOT, 'normalizer', m), m, quiet=True):
            rhs = process_text(rhs_map, ortho, Report()) if m in ('usage_map.tsv', 'calque_map.tsv') else rhs_map
            cands = []
            if rhs in best:
                cands.append(('exact', rhs, best[rhs]))
            for k in range(len(rhs) - 1, max(3, len(rhs) - MAX_SFX - 1), -1):
                if rhs[:k] in best:
                    cands.append(('stem', rhs[:k], best[rhs[:k]]))
                    break
            if cands:
                ev, form, r = min(cands, key=lambda c: (c[2]['status'] != 'verified', c[0] != 'exact'))
                row = [ev, form, r['source'], r['row_id'], r['scan'], r['status'] == 'verified' and 'yes' or 'no']
            else:
                row = ['none', '', '', '', '', '']
            rows.append([m, lhs, rhs_map, ' '.join(sorted(flags)), origin.get((m, lhs), '')] + row
                        + [old.get((m, lhs, rhs_map), '')])

    with open(OUT, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('# provenance.tsv — generated by tools/build_provenance.py; edit only the verdict column\n')
        w = csv.writer(fh, delimiter='\t', lineterminator='\n', quoting=csv.QUOTE_NONE, escapechar='\\')
        w.writerow(COLS)
        w.writerows(rows)
    from collections import Counter
    c = Counter((r[0], r[5], r[10]) for r in rows)
    for k in sorted(c):
        print(f'{k[0]:18} {k[1]:6} verified={k[2] or "-":4} {c[k]}')


if __name__ == '__main__':
    main()
